-- Настройка отступов в 4 пробела
vim.opt.shiftwidth = 4 -- Размер автоматического отступа (в пробелах)
vim.opt.tabstop = 4 -- Сколько пробелов занимает один символ табуляции
vim.opt.softtabstop = 4 -- Сколько пробелов вставляет нажатие клавиши Tab
vim.opt.expandtab = true -- Превращать ли нажатие Tab в пробелы
